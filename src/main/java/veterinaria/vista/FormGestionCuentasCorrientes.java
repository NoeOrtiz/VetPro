        boolean creando = "CreandoCuentaCorriente".equals(Application.consultarEstadoUsuario());
        boolean editando = "EditandoCuentaCorriente".equals(Application.consultarEstadoUsuario());

        String accion = creando ? "CREAR" : (editando ? "EDITAR" : "GUARDAR");
