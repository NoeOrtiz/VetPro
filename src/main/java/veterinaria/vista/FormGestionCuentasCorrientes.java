    private boolean validarDatosCuentaCorriente(){
        if (jcbCliente.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un cliente!");
            return false;
        }
        if (txtSaldoInicial.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "El saldo inicial no puede estar vacío.");
            return false;
        }
        if (txtLimiteDeCredito.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe ingresar un limite de crédito!");
            return false;
        }

        BigDecimal saldoInicial;
        BigDecimal limiteCredito;
        try {
            saldoInicial = parsearMonto(txtSaldoInicial.getText(), "saldo inicial");
            limiteCredito = parsearMonto(txtLimiteDeCredito.getText(), "límite de crédito");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Dato inválido", JOptionPane.WARNING_MESSAGE);
            return false;
        }

        if (saldoInicial.compareTo(BigDecimal.ZERO) < 0) {
            JOptionPane.showMessageDialog(this, "El saldo inicial no puede ser negativo.");
            return false;
        }
        if (limiteCredito.compareTo(BigDecimal.ZERO) < 0) {
            JOptionPane.showMessageDialog(this, "El límite de crédito no puede ser negativo.");
            return false;
        }

        if (jcbEstado.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar el estado de Cuenta Corriente!");
            return false;
        }
        return true;          
    }

    private BigDecimal parsearMonto(String valor, String nombreCampo) {
        String normalizado = valor != null ? valor.trim().replace(" ", "").replace(",", ".") : "";
        if (normalizado.isEmpty()) {
            throw new NumberFormatException("El campo " + nombreCampo + " no puede estar vacío.");
        }
        try {
            return new BigDecimal(normalizado);
        } catch (NumberFormatException ex) {
            throw new NumberFormatException("El campo " + nombreCampo + " debe contener un monto numérico válido.");
        }
    }

    private void persistirCuentaCorriente() {
        boolean creando = "CreandoCuentaCorriente".equals(Application.consultarEstadoUsuario());
        boolean editando = "EditandoCuentaCorriente".equals(Application.consultarEstadoUsuario());

        if (creando) {
            cuentaCorriente = new CuentaCorriente();
            cuentaCorriente.setFechaCreacion(LocalDate.now());
            // Al crear: saldo actual inicia en 0 (según tu lógica actual)
            cuentaCorriente.setSaldoActual(new BigDecimal(0));
        }

        BigDecimal saldoInicial = parsearMonto(txtSaldoInicial.getText(), "saldo inicial");
        BigDecimal limiteCredito = parsearMonto(txtLimiteDeCredito.getText(), "límite de crédito");

        // Datos que aplican tanto a crear como a editar
        cuentaCorriente.setCliente(cliente);
        cuentaCorriente.setSaldoInicial(saldoInicial);
        cuentaCorriente.setLimiteCredito(limiteCredito);
        cuentaCorriente.setUltimaEdicion(LocalDate.now());
        cuentaCorriente.setEstado(jcbEstado.getSelectedItem().toString());

        // En edición NO tocar saldoActual ni fechaCreacion (se preservan)
        if (creando) {
            try {
                if (operarCuentaCorriente.crearCuentaCorriente(cuentaCorriente)) {
                    JOptionPane.showMessageDialog(this, "Cuenta Corriente creada exitosamente.");
                } else {
                    JOptionPane.showMessageDialog(this, "Error al guardar una Cuenta Corriente!");
                }
            } catch (Exception ex) {
                Logger.getLogger(FormGestionCuentasCorrientes.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

        if (editando) {
            try {
                operarCuentaCorriente.actualizarCuentaCorriente(cuentaCorriente);
                JOptionPane.showMessageDialog(this, "Cuenta Corriente editada exitosamente.");
            } catch (Exception ex) {
                Logger.getLogger(FormGestionCuentasCorrientes.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }

