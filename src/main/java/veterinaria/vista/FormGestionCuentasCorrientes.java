    private void setBusy(boolean busy) {
        try {
            setCursor(busy ? java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.WAIT_CURSOR)
                           : java.awt.Cursor.getDefaultCursor());
        } catch (Exception ignored) {
        }
    }

    private void cargarInicialAsync() {
        setBusy(true);
        new SwingWorker<Void, Void>() {
            @Override
            protected Void doInBackground() {
                if (permitirRecalculoMasivo) {
                    operarCuentaCorriente.actualizarTodosLosSaldosCC();
                }
                return null;
            }

            @Override
            protected void done() {
                try {
                    cargarComboClientesTodosAsync();
                    cargarCuentasCorrientesEnTablaAsync();
                } finally {
                    setBusy(false);
                }
            }
        }.execute();
    }

