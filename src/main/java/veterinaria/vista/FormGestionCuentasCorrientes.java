    private void cargarCuentasCorrientesEnTablaAsync() {
        setBusy(true);
        new SwingWorker<List<Object[]>, Void>() {
            @Override
            protected List<Object[]> doInBackground() {
                List<CuentaCorriente> cuentasCorrientes = operarCuentaCorriente.buscarTodasLasCuentasCorrientes();
                ArrayList<Object[]> filas = new ArrayList<>();
                for (CuentaCorriente cc : cuentasCorrientes) {
                    Cliente c = operarClientes.buscarPorId(cc.getCliente().getIdCliente());
                    Object nombreCliente = (c != null && c.getPersona() != null)
                            ? (c.getPersona().getNombre() + " " + c.getPersona().getApellido())
                            : "";
                    filas.add(new Object[]{
                        false,
                        cc.getIdCuentaCorriente(),
                        nombreCliente,
                        cc.getSaldoActual(),
                        cc.getLimiteCredito(),
                        cc.getFechaCreacion(),
                        cc.getUltimaEdicion(),
                        cc.getEstado(),
                    });
                }
                return filas;
            }

            @Override
            protected void done() {
                try {
                    List<Object[]> filas = get();
                    DefaultTableModel modelo = (DefaultTableModel) tableCCClientes.getModel();
                    modelo.setRowCount(0);
                    for (Object[] f : filas) {
                        modelo.addRow(f);
                    }
                    operarTabla.asegurarSeleccionUnica(tableCCClientes);
                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(FormGestionCuentasCorrientes.this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                } finally {
                    setBusy(false);
                }
            }
        }.execute();
    }
    
