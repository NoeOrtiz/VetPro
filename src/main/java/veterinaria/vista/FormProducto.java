    private void cargarProductosEnTabla() {
        String filtroEstado = obtenerFiltroEstadoProductoSeleccionado();
        List<Producto> productos;

        if ("Todos".equalsIgnoreCase(filtroEstado)) {
            productos = operandoProducto.buscarTodosLosProductos();
        } else {
            productos = operandoProducto.buscarProductosPorEstado(filtroEstado);
        }

        // Configuración del formateador numérico para Argentina ($ 2.000,00)
        java.text.DecimalFormatSymbols simbolos = new java.text.DecimalFormatSymbols(new java.util.Locale("es", "AR"));
        simbolos.setGroupingSeparator('.');
        simbolos.setDecimalSeparator(',');

        java.text.DecimalFormat formateador = new java.text.DecimalFormat();
        formateador.setDecimalFormatSymbols(simbolos);
        formateador.applyPattern("$ #,##0.00");
        formateador.setGroupingUsed(true);

        // Si aún no inicializaste el modelo en el constructor, puedes inicializarlo aquí una vez o tenerlo como variable global.
        // Lo ideal es que modeloProductos sea un atributo de tu clase FormProducto.
        if (modeloProductos == null) {
            String[] columnas = {
                "Seleccionar", "ID", "Código", "Nombre", "Rubro", "Descripción", "Precio Costo", "Precio Venta", "Unidad de Medida", "Stock Actual"
            };

            modeloProductos = operarTablas.configurarTablaGenerica(tableProductos, columnas, (productoBucle, columnIndex) -> {
                if (productoBucle == null) {
                    return null;
                }

                Double precioVentaMostrar = productoBucle.getPrecio();
                if (precioVentaMostrar == null && productoBucle.getPrecioCosto() != null) {
                    double costo = productoBucle.getPrecioCosto();
                    double iva = 21.0;
                    try {
                        if (productoBucle.getIva() != null) {
                            String ivaLimpio = productoBucle.getIva().replaceAll("[^0-9.]", "");
                            if (!ivaLimpio.isEmpty()) {
                                iva = Double.parseDouble(ivaLimpio);
                            }
                        }
                    } catch (Exception e) {
                        iva = 0.0;
                    }
                    precioVentaMostrar = Math.round((costo * (1 + (iva / 100))) * 100.0) / 100.0;
                } else if (precioVentaMostrar == null) {
                    precioVentaMostrar = 0.0;
                }

                Integer stockMostrar = productoBucle.getStock() != null ? productoBucle.getStock() : 0;

                String costoFormateado = formateador.format(productoBucle.getPrecioCosto() != null ? productoBucle.getPrecioCosto() : 0.0);
                String ventaFormateada = formateador.format(precioVentaMostrar);
                String unidadMostrar = productoBucle.getUmedida() != null ? productoBucle.getUmedida() : "";

                switch (columnIndex) {
                    case 1:
                        return productoBucle.getIdProducto();
                    case 2:
                        return productoBucle.getCodigo();
                    case 3:
                        return productoBucle.getNombre();
                    case 4:
                        return productoBucle.getRubro();
                    case 5:
                        return productoBucle.getDescripcion();
                    case 6:
                        return costoFormateado;
                    case 7:
                        return ventaFormateada;
                    case 8:
                        return unidadMostrar;
                    case 9:
                        return stockMostrar;
                    default:
                        return null;
                }
            });

            operarTablas.ocultarColumnaId(tableProductos, 1);
        }

        // Simplemente le pasamos la lista de productos al modelo genérico de forma limpia y segura
        modeloProductos.cargarDatos(productos);

        btnEditar.setEnabled(false);
        btnEliminar.setEnabled(false);
        btnImprimir.setVisible(false);
        actualizarTabla();
    }

    private void actualizarTabla() {     // Método para asegurar solamente selección de 1 fila para operar.
        if (listenerSeleccionUnicaInstalado) {
            return;
        }

        tableProductos.getModel().addTableModelListener(e -> {
            if (e.getColumn() == 0) {
                int rowCount = tableProductos.getRowCount();
                for (int i = 0; i < rowCount; i++) {
                    Object valor = tableProductos.getValueAt(i, 0);
                    boolean seleccionado = valor instanceof Boolean && (Boolean) valor;
                    if (i != e.getFirstRow() && seleccionado) {
                        tableProductos.setValueAt(false, i, 0);
                    }
                }
            }
        });
        listenerSeleccionUnicaInstalado = true;
    }

