    private void imprimirListaProductosConFiltro(ReporteSelectorUtil.Formato formato, String rubroFiltro) {
        ReporteRequest req = new ReporteRequest()
                .put("tabla", tableProductos)
                .put("emisor", Application.getNombreApellidoUsuarioLogeado())
                .put("rubroFiltro", rubroFiltro) // 🌟 Asegúrate de que coincida con el que lee el PDF
                .put("FORMATO_REPORTE", formato);

        veterinaria.reportes.pdf.ReporteEjecutor.ejecutarConAviso(this, ReporteTipo.PRODUCTO_LISTADO, req);
    }

    private Producto obtenerProductoSeleccionadoDesdeTabla() {
        int row = operarTablas.comprobarElementoSeleccionado(tableProductos);
        if (row == -1) {
            JOptionPane.showMessageDialog(this,
                    "Debe seleccionar un producto de la lista.",
                    "Atención",
                    JOptionPane.WARNING_MESSAGE);
            return null;
        }

        Object idObj = tableProductos.getValueAt(row, 1);
        Integer id = null;
        try {
            id = Integer.valueOf(String.valueOf(idObj));
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo obtener el ID del producto seleccionado.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return null;
        }

        Producto p = operandoProducto.buscarProductoPorId(id);
        if (p == null) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el producto seleccionado en la base de datos.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return null;
        }
        return p;
    }

    private double obtenerDescuentoNormalizado() {
        String descuentoTexto = txtDescuento.getText() != null ? txtDescuento.getText().trim() : "";
        if (descuentoTexto.isEmpty()) {
            return 0d;
        }
        descuentoTexto = descuentoTexto.replace(",", ".");
        return Double.parseDouble(descuentoTexto);
    }

    private String obtenerDescuentoParaPersistencia() {
        double descuento = obtenerDescuentoNormalizado();
        if (descuento == Math.rint(descuento)) {
            return String.valueOf((long) descuento);
        }
        return String.valueOf(descuento);
    }

    private boolean eliminarProductoSeleccionado() {
        Integer selectedRow = operarTablas.comprobarElementoSeleccionado(tableProductos);
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Por favor seleccione un producto a ELIMINAR", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return false;
        }

        // Obtenemos el ID de la tabla (asegúrate de que el índice de columna de tu ID sea el correcto, ej: 1)
        Integer idProducto = (Integer) tableProductos.getValueAt(selectedRow, 1);

        // Delegamos la operación al controlador que ya creamos
        boolean exito = operandoProducto.eliminarProductoPorId(idProducto);

        if (!exito) {
            JOptionPane.showMessageDialog(null, "No se pudo eliminar el producto seleccionado.", "Error", JOptionPane.ERROR_MESSAGE);
        }

        return exito;
    }

    private boolean editarProductoSeleccionado() {
        int selectedRow = operarTablas.comprobarElementoSeleccionado(tableProductos);
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "¡Debe seleccionar un producto a EDITAR!", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return false;
        }

        // Leemos la celda del ID de forma segura (asegúrate de que el índice '1' sea el de la columna ID)
        Object valorId = tableProductos.getValueAt(selectedRow, 1);
        if (valorId == null) {
            JOptionPane.showMessageDialog(null, "No se pudo obtener el identificador del producto.", "Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }

        // Convertimos a String primero y luego a Integer para evitar cualquier ClassCastException
        Integer idProducto = Integer.valueOf(valorId.toString().trim());

        // Buscamos en el controlador usando el método que ya tienes
        producto = operandoProducto.buscarProductoPorId(idProducto);

        if (producto == null) {
            JOptionPane.showMessageDialog(null, "No se encontró el producto en la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }

        // Asignación de campos al formulario...
        proveedor = producto.getProveedor();
        txtCodigo.setText(producto.getCodigo());
        txtCodigo.setEnabled(false);
        txtNombre.setText(producto.getNombre());
        jcbRubro.setSelectedItem(producto.getRubro());
        txtDescripcion.setText(producto.getDescripcion());
        txtPrecio.setText(String.valueOf(producto.getPrecioCosto()));
        jcbIva.setSelectedItem(String.valueOf(producto.getIva()));
        txtDescuento.setText(String.valueOf(producto.getDescuento() != null ? producto.getDescuento() : "0"));
        jcbUMedida.setSelectedItem(producto.getUmedida());
        seleccionarProveedorEnCombo(producto.getProveedor() != null ? producto.getProveedor().getIdProveedor() : null);
        jcbEstado.setSelectedItem(producto.getEstado());
        txtStockInicial.setText(String.valueOf(producto.getStock() != null ? producto.getStock() : 0));
        txtStockMinimo.setText(String.valueOf(producto.getStockMinimo() != null ? producto.getStockMinimo() : 0));

        return true;
    }

    private Double parseDoublePrecio(String raw) {
        if (raw == null) {
            return 0.0;
        }
        // Normaliza coma decimal a punto
        String v = raw.trim().replace(" ", "").replace(",", ".");
        return Double.valueOf(v);
    }

