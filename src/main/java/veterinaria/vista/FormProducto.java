    private String construirResumenProducto(Producto p, String encabezado) {
        String proveedorTexto = (p != null && p.getProveedor() != null && p.getProveedor().getRazonSocial() != null)
                ? p.getProveedor().getRazonSocial()
                : "Sin proveedor";

        return encabezado + "\n\n"
                + "Código: " + safe(p != null ? p.getCodigo() : null) + "\n"
                + "Nombre: " + safe(p != null ? p.getNombre() : null) + "\n"
                + "Rubro: " + safe(p != null ? p.getRubro() : null) + "\n"
                + "Descripción: " + safe(p != null ? p.getDescripcion() : null) + "\n"
                + "Precio: " + (p != null && p.getPrecioCosto() != null ? p.getPrecioCosto() : 0.0) + "\n"
                + "IVA: " + safe(p != null ? p.getIva() : null) + "\n"
                + "Descuento: " + safe(p != null ? p.getDescuento() : null) + "\n"
                + "Unidad de medida: " + safe(p != null ? p.getUmedida() : null) + "\n"
                + "Proveedor: " + proveedorTexto + "\n"
                + "Estado: " + safe(p != null ? p.getEstado() : null) + "\n"
                + "Stock inicial: " + (p != null && p.getStock() != null ? p.getStock() : 0) + "\n"
                + "Stock mínimo: " + (p != null && p.getStockMinimo() != null ? p.getStockMinimo() : 0);
    }

    private String safe(String valor) {
        return valor == null || valor.trim().isEmpty() ? "-" : valor.trim();
    }

