    private String valorCombo(javax.swing.JComboBox<?> combo) {
        Object item = combo.getSelectedItem();
        return item != null ? item.toString().trim() : "";
    }

    private Proveedor obtenerProveedorSeleccionado() {
        Object selProv = jcbProveedor.getSelectedItem();
        if (selProv instanceof ProveedorItem) {
            ProveedorItem pi = (ProveedorItem) selProv;
            if (pi.getIdProveedor() != null && pi.getIdProveedor() != 0) {
                return operandoProveedor.buscarProveedorPorId(pi.getIdProveedor());
            }
        }
        return null;
    }

    private void seleccionarProveedorEnCombo(Integer idProveedor) {
        if (idProveedor == null) {
            jcbProveedor.setSelectedIndex(0);
            return;
        }
        for (int i = 0; i < jcbProveedor.getItemCount(); i++) {
            ProveedorItem item = jcbProveedor.getItemAt(i);
            if (item != null && idProveedor.equals(item.getIdProveedor())) {
                jcbProveedor.setSelectedIndex(i);
                return;
            }
        }
        jcbProveedor.setSelectedIndex(0);
    }

    private Producto construirProductoDesdeFormulario() {
        Producto p = new Producto();

        // Recuperar ID si estamos editando
        if (this.producto != null && this.producto.getIdProducto() != null) {
            p.setIdProducto(this.producto.getIdProducto());
        }

        p.setCodigo(txtCodigo.getText().trim());
        p.setNombre(txtNombre.getText().trim());
        p.setRubro(valorCombo(jcbRubro));
        p.setDescripcion(txtDescripcion.getText().trim());

        try {
            // 1. Lo que ingresas en pantalla se guarda como Precio Costo
            p.setPrecioCosto(parseDoublePrecio(txtPrecio.getText()));
        } catch (Exception ex) {
            p.setPrecioCosto(0.0);
        }

        p.setIva(valorCombo(jcbIva));
        p.setDescuento(obtenerDescuentoParaPersistencia());
        p.setUmedida(valorCombo(jcbUMedida));
        p.setProveedor(obtenerProveedorSeleccionado());
        p.setEstado(valorCombo(jcbEstado));

        try {
            p.setStock(Integer.valueOf(txtStockInicial.getText().trim()));
        } catch (Exception ex) {
            p.setStock(0);
        }
        try {
            p.setStockMinimo(Integer.valueOf(txtStockMinimo.getText().trim()));
        } catch (Exception ex) {
            p.setStockMinimo(0);
        }

        return p;
    }

