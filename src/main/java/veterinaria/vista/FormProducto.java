    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        normalizarCamposProducto();

        // Construimos el objeto con los datos de la interfaz
        Producto p = construirProductoDesdeFormulario();
        String estadoActual = Application.consultarEstadoUsuario();
        boolean esNuevo = "CreandoProducto".equals(estadoActual);

        // Confirmaciones visuales mediante JOptionPane
        if (esNuevo && !confirmarAltaProducto()) {
            return;
        }
        if (!esNuevo && !confirmarEdicionProducto()) {
            return;
        }

        try {
            // Delegamos todo al controlador/capa de negocio (Aquí se calcula el precio y se guarda)
            String codigoOriginal = esNuevo ? "" : p.getCodigo();
            boolean exito = operandoProducto.validarYGuardarProducto(p, esNuevo, codigoOriginal);

            if (exito) {
                // Mensaje de éxito correspondiente
                JOptionPane.showMessageDialog(this, esNuevo ? "Producto guardado exitosamente." : "Producto editado exitosamente.");

                // --- ACCIONES POST-GUARDADO EXITOSO (Recuperadas de tu versión anterior) ---
                limpiarCamposFormulario();
                cargarProductosEnTabla();

                // Manejo de paneles (puedes usar tu método mostrarPanelLista() o las líneas manuales)
                mostrarPanelLista();

                // Restablecer estados de botones si tu lógica lo requiere
                btnNuevo.setEnabled(true);
                btnEditar.setEnabled(false);
                btnEliminar.setEnabled(false);
                btnImprimir.setVisible(false);
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo guardar el producto.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (IllegalArgumentException ex) {
            // Capturamos cualquier regla de negocio rota (incluyendo el Logger si ocurre en el controlador)
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Atención", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

