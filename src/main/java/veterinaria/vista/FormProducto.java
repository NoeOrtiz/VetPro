    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String perm = "FormProducto.ELIMINAR";
        if (sesion == null || !sesion.puede(perm)) {
            JOptionPane.showMessageDialog(
                    null,
                    "No tienes permisos suficientes para eliminar productos.",
                    "Acceso restringido",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Application.actualizarEstadoUsuario("EliminandoProducto");

        // Obtenemos el producto seleccionado de la tabla solo para mostrar su nombre en la confirmación
        Producto seleccionado = obtenerProductoSeleccionadoDesdeTabla();
        if (seleccionado == null) {
            return;
        }

        if (!confirmarEliminacionProducto(seleccionado)) {
            Application.actualizarEstadoUsuario("Eliminación cancelada");
            return;
        }

        // Delegamos la eliminación al método que interactúa con el controlador
        if (eliminarProductoSeleccionado()) {
            JOptionPane.showMessageDialog(null, "Producto eliminado con éxito", "Información", JOptionPane.INFORMATION_MESSAGE);
            mostrarPanelLista();
            return;
        }
    }//GEN-LAST:event_btnEliminarActionPerformed
    private void btnImprimirListaActionPerformed(java.awt.event.ActionEvent evt) {
        if (tableProductos.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No hay datos en la tabla para exportar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Desplegamos el Pop-up para elegir el filtro de impresión
        JPopupMenu menuFiltro = new JPopupMenu();

        JMenuItem itemTodos = new JMenuItem("Todos los Productos");
        itemTodos.addActionListener(e -> solicitarFormatoEImprimir("TODOS"));
        menuFiltro.add(itemTodos);

        menuFiltro.addSeparator();

        // Cargamos los rubros activos dinámicamente desde el servicio
        try {
            List<String> rubrosDb = rubroService.listarNombresActivos();
            if (rubrosDb != null) {
                for (String rubro : rubrosDb) {
                    if (rubro != null && !rubro.trim().isEmpty()) {
                        JMenuItem itemRubro = new JMenuItem("Rubro: " + rubro.trim());
                        itemRubro.addActionListener(e -> solicitarFormatoEImprimir(rubro.trim()));
                        menuFiltro.add(itemRubro);
                    }
                }
            }
        } catch (Exception ex) {
            System.err.println("Error al cargar rubros para el menú: " + ex.getMessage());
        }

        menuFiltro.show(btnImprimirLista, 0, btnImprimirLista.getHeight());
    }
